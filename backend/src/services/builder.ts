  private static detectDotnetProject(files: string[], project: any): string {
    logger.info('Detected .NET project');
    const rawProjFile = files.find(f => f.endsWith('.csproj') || f.endsWith('.fsproj'));
    const safeProjFile = rawProjFile ? rawProjFile.replace(/[^a-zA-Z0-9._-]/g, '') : '';
    const csproj = safeProjFile || '*.csproj';
    const dllName = safeProjFile ? safeProjFile.replace(/\.(csproj|fsproj)$/i, '.dll') : 'app.dll';
    const customBuild = project.buildCommand ? this.sanitizeShellLine(String(project.buildCommand)) : '';
    const startCmd = project.startCommand || `dotnet ${dllName}`;
    return `
FROM mcr.microsoft.com/dotnet/sdk:8.0 AS builder
WORKDIR /app
COPY ["${csproj}", "./"]
RUN dotnet restore
COPY . .
${customBuild ? `RUN ${customBuild}\n` : ''}RUN dotnet publish -c Release -o out
FROM mcr.microsoft.com/dotnet/aspnet:8.0
WORKDIR /app
COPY --from=builder /app/out .
ENV ASPNETCORE_URLS=http://+:8080 PORT=8080
EXPOSE 8080
${this.cmdFrom(startCmd)}
    `;
  }

  public static async buildProject(
    deploymentId: string,
    projectId: string,
    zipPath?: string,
    gitOptions?: { repoUrl: string; branch: string; subdir?: string }
  ) {
    const storageDir = path.join(process.cwd(), 'storage', 'projects', projectId);
    const sourceDir = path.join(storageDir, 'source');
    const buildTempDir = path.join(process.cwd(), 'tmp', 'builds', deploymentId);
    const cloneTempDir = path.join(process.cwd(), 'tmp', 'clones', deploymentId);

    const { io } = await import('../index.js');
    const capturedLogLines: string[] = [];
    let capturedBytes = 0;
    const MAX_STORED_LOG_BYTES = 100 * 1024;
    const appendCapturedLog = (line: string) => {
      const cleanLine = line.trimEnd();
      if (!cleanLine) return;
      const lineBytes = Buffer.byteLength(cleanLine, 'utf8') + 1;
      capturedLogLines.push(cleanLine);
      capturedBytes += lineBytes;
      while (capturedBytes > MAX_STORED_LOG_BYTES && capturedLogLines.length > 1) {
        const dropped = capturedLogLines.shift()!;
        capturedBytes -= Buffer.byteLength(dropped, 'utf8') + 1;
      }
    };

    const emitLog = (message: string) => {
      const trimmed = message.trim();
      if (!trimmed) return;
      appendCapturedLog(trimmed);
      io.to(`project:${projectId}`).emit('log', {
        type: 'build',
        message: trimmed,
        timestamp: new Date().toISOString()
      });
    };

    try {
      const project = await prisma.project.findUnique({ where: { id: projectId } });
      if (!project) throw new Error('Project not found');

      await prisma.deployment.update({
        where: { id: deploymentId },
        data: { status: 'building' },
      });
      await prisma.project.update({
        where: { id: projectId },
        data: { status: 'building' },
      });

      if (zipPath) {
        emitLog('> Reading your code...');
        await fs.ensureDir(sourceDir);
        await fs.emptyDir(sourceDir);
        await this.extractZip(zipPath, sourceDir);
      } else if (gitOptions) {
        emitLog(`> Cloning repository from GitHub...`);
        emitLog(`> Branch: ${gitOptions.branch}${gitOptions.subdir ? `, Directory: ${gitOptions.subdir}` : ''}`);
        await fs.ensureDir(sourceDir);
        await fs.emptyDir(sourceDir);
        await fs.ensureDir(cloneTempDir);

        try {
          const clonedPath = await this.cloneRepo(
            gitOptions.repoUrl,
            gitOptions.branch,
            cloneTempDir,
            gitOptions.subdir
          );
          // Copy cloned content to sourceDir without preserving symlinks
          await fs.copy(clonedPath, sourceDir, { overwrite: true, dereference: false });
          await this.stripSymlinksRecursive(sourceDir);
          emitLog('> Repository cloned successfully!');
        } finally {
          await fs.remove(cloneTempDir).catch(() => {});
        }
      } else {
        await this.stripSymlinksRecursive(sourceDir);
      }

      emitLog('> Determining the best way to run your app...');
      await this.detectAndGenerateDockerfile(sourceDir, project);

      // Write a default .dockerignore if absent so heavy folders & secrets aren't sent to Docker daemon
      const dockerignorePath = path.join(sourceDir, '.dockerignore');
      if (!(await fs.pathExists(dockerignorePath))) {
        await fs.writeFile(dockerignorePath, '.git\nnode_modules\n.next\n.env\n.env.*\n', 'utf8');
      }

      // Pack source while excluding node_modules and .git from Docker context
      await fs.ensureDir(buildTempDir);
      const tarStream = tar.pack(sourceDir, {
        ignore: (name) => {
          const rel = path.relative(sourceDir, name).replace(/\\/g, '/');
          return (
            rel === '.git' ||
            rel.startsWith('.git/') ||
            rel === 'node_modules' ||
            rel.startsWith('node_modules/')
          );
        },
      });
      const imageName = `codehost-project-${projectId.toLowerCase()}:${deploymentId}`;

      emitLog('> Building your app...');

      const isFreeTier = !project?.tier || project.tier === 'free';
      const buildTimeoutMs = isFreeTier ? 180_000 : 600_000; // 3m free, 10m paid
      const buildMemoryBytes = isFreeTier ? 512 * 1024 * 1024 : 2048 * 1024 * 1024;
      const buildCpuShares = isFreeTier ? 256 : 1024;

      const stream = await docker.buildImage(tarStream, {
        t: imageName,
        memory: buildMemoryBytes,
        cpushares: buildCpuShares,
      });

      await new Promise((resolve, reject) => {
        let settled = false;
        const timer = setTimeout(() => {
          if (settled) return;
          settled = true;
          try {
            (stream as any).destroy?.();
          } catch {}
          reject(new Error(`Build timed out after ${Math.round(buildTimeoutMs / 1000)}s (${isFreeTier ? 'Free tier limit — upgrade for 10m priority builds' : 'build limit'})`));
        }, buildTimeoutMs);

        docker.modem.followProgress(
          stream,
          (err, res) => {
            if (settled) return;
            settled = true;
            clearTimeout(timer);
            if (err) return reject(err);
            // Check the last result in the stream for internal build errors
            const lastMessage = Array.isArray(res) ? res[res.length - 1] : res;
            if (lastMessage && lastMessage.error) {
              return reject(new Error(lastMessage.error));
            }
            resolve(res);
          },
          (progress) => {
            if (progress.stream) {
              emitLog(progress.stream);
            }
            if (progress.error) {
              emitLog(`> Error during build: ${progress.error}`);
            }
          }
        );
      });

      emitLog('> Success! Preparing to launch...');
      await prisma.deployment.update({
        where: { id: deploymentId },
        data: { logs: capturedLogLines.join('\n') },
      }).catch(() => {});
      logger.info(`Successfully built image ${imageName}`);
      return imageName;
    } catch (error: any) {
      emitLog(`> Something went wrong: ${error.message || 'Unknown error'}`);
      logger.error(`Build failed for deployment ${deploymentId}`, error);
      await prisma.deployment.update({
        where: { id: deploymentId },
        data: {
          status: 'failed',
          logs: capturedLogLines.join('\n'),
        },
      }).catch(() => {});
      await prisma.project.update({
        where: { id: projectId },
        data: { status: 'failed' },
      }).catch(() => {});
      throw error;
    } finally {
      await fs.remove(buildTempDir).catch((e) => logger.warn(`Failed to cleanup buildTempDir ${buildTempDir}`, e));
      await fs.remove(cloneTempDir).catch(() => {});
    }
  }
